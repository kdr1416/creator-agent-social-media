# ── the retired Gemini target ─────────────────────────────────


class TestRetiredGeminiTarget:
    def test_gemini_is_not_a_generator_any_more(self, setup_mod):
        assert "gemini" not in setup_mod.TOOLS
        assert set(setup_mod.TOOLS) == {"claude", "codex", "antigravity"}
        assert not hasattr(setup_mod, "generate_gemini")
        assert not hasattr(setup_mod, "generate_gemini_md")

    def test_antigravity_generator_creates_skills(self, setup_mod, sandbox):
        skills = setup_mod.discover_skills()
        count = setup_mod.generate_antigravity(skills)
        assert count > 0
        assert (sandbox / ".agents" / "skills" / "fk-demo" / "SKILL.md").exists()


    def test_a_stale_state_file_naming_gemini_does_not_crash_sync(
        self, setup_mod, sandbox, capsys
    ):
        """`.fk-setup.json` written before v1.3.1 records "gemini". A sync that
        raised on it would strand the user with no way to regenerate the
        targets that do still exist."""
        skills = setup_mod.discover_skills()
        setup_mod.run_generators(["claude", "gemini", "codex"], skills)

        out = capsys.readouterr().out
        assert "Skipping 'gemini'" in out
        assert "setup.py clean" in out          # and says how to tidy up
        assert (sandbox / "AGENTS.md").exists()  # the live targets still ran
        assert list((sandbox / ".claude" / "commands").glob("fk-*.md"))

    def test_clean_removes_what_the_gemini_target_left_behind(self, setup_mod, sandbox):
        """Nothing writes these any more, so `clean` is the only thing that
        will ever take them away from an install made before v1.3.1."""
        legacy_dir = sandbox / ".gemini" / "commands" / "fk"
        legacy_dir.mkdir(parents=True)
        (legacy_dir / "demo.toml").write_text('description = "x"\n', encoding="utf-8")
        (sandbox / "GEMINI.md").write_text(
            "<!-- AUTO-GENERATED by setup.py — do not edit. Source: skills/ -->\n# old\n",
            encoding="utf-8",
        )

        setup_mod.do_clean()

        assert not (legacy_dir / "demo.toml").exists()
        assert not (sandbox / "GEMINI.md").exists()
        assert not (sandbox / ".gemini").exists()  # the empty tree goes too

    def test_clean_leaves_a_hand_written_instruction_file_alone(self, setup_mod, sandbox):
        """`clean` keys off the generated header. A file someone wrote
        themselves must survive it."""
        (sandbox / "GEMINI.md").write_text("# My own notes, not generated\n")
        (sandbox / "AGENTS.md").write_text("# Hand-written\n")

        setup_mod.do_clean()

        assert (sandbox / "GEMINI.md").exists()
        assert (sandbox / "AGENTS.md").exists()


# ── AGENTS.md is generated, and must stay lossless ────────────


class TestGeneratedAgentsMdIsComplete:
    """Pin durable V2 routing and operational safeguards through regeneration."""

    @pytest.fixture
    def generated(self, setup_mod, sandbox):
        setup_mod.generate_codex(setup_mod.discover_skills())
        return (sandbox / "AGENTS.md").read_text(encoding="utf-8")

    @pytest.mark.parametrize("marker", [
        "## 1. Global Rules", "## 2. Workflow Routing", "## 3. Engine Routing",
        "## 4. Creative Contracts", "## 5. Skill Discovery",
        "Codex Full Production", "Human Approval", "Review generated video before upscale",
        "Fact-check factual claims", "codebase-memory",
    ])
    def test_v2_contract_survives_regeneration(self, generated, marker):
        assert marker in generated

    def test_exactly_five_top_level_blocks_and_no_stale_rules(self, generated):
        assert len([s for s in generated.splitlines() if s.startswith("## ")]) == 5
        for obsolete in ("Before ANY workflow", "180–200", "180-200", "70–80%", "Real-people bypass"):
            assert obsolete not in generated
        assert "Pure 2D work requires no Google Flow" in generated
        assert "No fixed footer" in generated

    def test_the_skill_table_is_built_from_the_skills_directory(self, generated):
        """The committed file had drifted to 25 skills — missing 11 that exist
        and listing one that does not. Deriving it at generation time is what
        stops that happening again."""
        assert "| `/fk-demo` |" in generated

    def test_the_generated_file_is_marked_generated(self, generated):
        assert generated.splitlines()[0].startswith("<!-- AUTO-GENERATED by setup.py")


